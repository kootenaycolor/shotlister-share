//! **How wide a word is on the printed page**, without a font library.
//!
//! The table export is set in the system font (`-apple-system`, which WebKit
//! draws as SF Pro), and Auto layout (`autolayout`) has to know how long a
//! word will be before WebKit lays it out — that is how it can promise a
//! column is never narrower than its longest word. These are that font's own
//! advance widths, read off CoreText once at 10pt and kept here in
//! thousandths of an em, for U+0020 to U+024F (every Latin letter he is
//! likely to type) plus the punctuation a shot list uses. Anything outside
//! falls back to an average letter, which errs wide.
//!
//! Regenerate with the script in `engine/tools/font-metrics.swift` if the
//! export ever changes typeface.

/// Which cut of the face a run of text is set in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Weight {
    Regular,
    Semibold,
    Bold,
}

/// The width of `text` in ems of its own size, before any letter-spacing.
pub fn em_width(text: &str, weight: Weight) -> f64 {
    text.chars().map(|c| advance(c, weight)).sum()
}

/// One letter's advance, in ems.
pub fn advance(c: char, weight: Weight) -> f64 {
    let (table, extra): (&[u16], &[(char, u16)]) = match weight {
        Weight::Regular => (&REGULAR, &REGULAR_EXTRA),
        Weight::Semibold => (&SEMIBOLD, &SEMIBOLD_EXTRA),
        Weight::Bold => (&BOLD, &BOLD_EXTRA),
    };
    let code = c as u32;
    let thousandths = if (0x20..0x20 + table.len() as u32).contains(&code) {
        match table[(code - 0x20) as usize] {
            0 => FALLBACK,
            w => w,
        }
    } else if let Some((_, w)) = extra.iter().find(|(k, _)| *k == c) {
        *w
    } else if c == '\u{a0}' || c == '\t' {
        table[0]
    } else if (c as u32) >= 0x2E80 {
        // A CJK character or an emoji is about a square.
        1000
    } else {
        FALLBACK
    };
    thousandths as f64 / 1000.0
}

