//! SHA-256.
//!
//! Media is identified by what is in it rather than where it came from, which is
//! what makes the same reference frame used across eight shots one stored file,
//! and what stops sync transferring a frame it already has.
//!
//! Written out rather than pulled in, so the core stays dependency-free and the
//! hash is guaranteed identical on macOS, iOS and in WebAssembly. Checked against
//! the published test vectors.

use std::fmt;

#[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Hash256(pub [u8; 32]);

impl Hash256 {
    pub fn to_hex(&self) -> String {
        let mut out = String::with_capacity(64);
        for byte in self.0 {
            out.push_str(&format!("{byte:02x}"));
        }
        out
    }

    pub fn from_hex(s: &str) -> Option<Hash256> {
        if s.len() != 64 {
            return None;
        }
        let mut bytes = [0u8; 32];
        for (i, byte) in bytes.iter_mut().enumerate() {
            *byte = u8::from_str_radix(s.get(i * 2..i * 2 + 2)?, 16).ok()?;
        }
        Some(Hash256(bytes))
    }

    /// Short form for file names and debugging. Sixteen hex characters is ample
    /// for one project's media library.
    pub fn short(&self) -> String {
        self.to_hex()[..16].to_string()
    }
}

impl fmt::Display for Hash256 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.to_hex())
    }
}

impl fmt::Debug for Hash256 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "Hash({}…)", &self.to_hex()[..8])
    }
}

